"""Create wholly synthetic, non-human input and a reproducible demonstration."""

from __future__ import annotations

import csv
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont


def build_demo(directory: str | Path) -> tuple[Path, Path]:
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    image_path = directory / "synthetic_stimulus.png"
    image = Image.new("RGB", (1280, 720), "#F4F4F1")
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle((90, 90, 570, 610), radius=35, fill="#0C2B47")
    draw.rounded_rectangle((710, 90, 1190, 610), radius=35, fill="#F6D98B", outline="#4B3B2A", width=3)
    draw.text((180, 310), "DESIGN A", fill="white", font=ImageFont.load_default())
    draw.text((870, 310), "DESIGN B", fill="#30200F", font=ImageFont.load_default())
    draw.text((470, 665), "SYNTHETIC STIMULUS - NOT HUMAN RESEARCH DATA", fill="#404040")
    image.save(image_path)
    raw_path = directory / "synthetic_imotions_export.csv"
    rng = np.random.default_rng(2023)
    cols = ["Row", "Timestamp", "SlideEvent", "StimType", "SourceStimuliName",
            "ET_GazeLeftx", "ET_GazeLefty", "ET_GazeRightx", "ET_GazeRighty", "Joy", "Engagement"]
    rows = []
    index = 1
    rows.append([index, 0, "StartSlide", "TestImage", "synthetic_stimulus"] + [""] * 6)
    index += 1
    rows.append([index, 10, "StartMedia", "TestImage", "synthetic_stimulus"] + [""] * 6)
    index += 1
    for n in range(330):
        timestamp = 16 * (n + 1)
        x = float(np.clip(rng.normal(360 if n < 170 else 940, 105), 0, 1279))
        y = float(np.clip(rng.normal(340, 90), 0, 719))
        rows.append([index, timestamp, "", "", "synthetic_stimulus", x, y,
                     x + rng.normal(2, 2), y + rng.normal(2, 2), "", ""])
        index += 1
        if n % 5 == 0:
            rows.append([index, timestamp + 3, "", "", "synthetic_stimulus",
                         "", "", "", "", float(np.clip(rng.normal(0.25 if n < 170 else 0.8, .07), 0, 1)), .5])
            index += 1
    rows.append([index, 5340, "EndMedia", "", "synthetic_stimulus"] + [""] * 6)
    with raw_path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["iMotions synthetic illustration - generated by this repository"])
        writer.writerow(["No human or participant recordings are included"])
        writer.writerow(cols)
        writer.writerows(rows)
    return raw_path, image_path
